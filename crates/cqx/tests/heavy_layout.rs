use cqx_vfs::Vfs;

fn findings(files: &[(&str, &str)], language: &str, rule: &str) -> u64 {
    let mut vfs = Vfs::new("heavy-layout");
    for (path, source) in files {
        vfs.insert(*path, *source);
    }
    let mut facts = Vec::new();
    let stats = cqx_analysis::run(&vfs, &mut facts).unwrap();
    assert!(stats.unparsed.is_empty(), "{:?}", stats.unparsed);
    let stream = cqx_store::facts::Stream::from_ndjson(&String::from_utf8(facts).unwrap());
    let config = cqx_score::config::Config::from_text(None).unwrap();
    let report = cqx_score::report_json(
        &config,
        &cqx_score::metrics::Metrics::compute(&stream, &config),
    );
    report["rules"]
        .as_array()
        .unwrap()
        .iter()
        .find(|r| r["language"] == language && r["rule"] == rule)
        .and_then(|r| r["total_findings"].as_u64())
        .unwrap_or(0)
}

#[test]
fn heavy_anchored_exclusions_and_real_generated_markers() {
    for (language, extension, manifest, source) in [
        (
            "c",
            "c",
            "CMakeLists.txt",
            "#include <stdlib.h>\nvoid f(void){exit(1);}",
        ),
        (
            "cpp",
            "cpp",
            "CMakeLists.txt",
            "#include <cstdlib>\nvoid f(){std::exit(1);}",
        ),
        (
            "csharp",
            "cs",
            "Library.csproj",
            "class L { void F(){Environment.Exit(1);} }",
        ),
    ] {
        let manifest = format!("nested/{manifest}");
        let product = format!("nested/src/domain/build/Library.{extension}");
        let excluded = format!("nested/build/Library.{extension}");
        let generated = format!("nested/src/Generated.{extension}");
        let ordinary =
            format!("// Values generated by this algorithm; do not edit the result.\n{source}");
        assert_eq!(
            findings(
                &[
                    (&manifest, ""),
                    (&product, &ordinary),
                    (&excluded, source),
                    (&generated, "// @generated\ninvalid source")
                ],
                language,
                "exit-in-library"
            ),
            1
        );
    }
}

